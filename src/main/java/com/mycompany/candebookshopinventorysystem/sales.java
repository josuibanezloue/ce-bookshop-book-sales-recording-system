private void loadBooks() {
    cmbBook.removeAllItems();

    String sql =
        "SELECT book_id, book_name FROM books "
      + "WHERE quantity > 0 AND status = 'Active' "
      + "ORDER BY book_name";

    try (Connection con = getConnection();
         PreparedStatement pst = con.prepareStatement(sql);
         ResultSet rs = pst.executeQuery()) {

        while (rs.next()) {
            cmbBook.addItem(
                rs.getString("book_name")
            );
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this,
            "Error loading books: " + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE);
    }
}

private void searchSales() {

    String search = txtSearch.getText().trim();

    DefaultTableModel model =
            (DefaultTableModel) tblSales.getModel();

    model.setRowCount(0);

    String sql =
            "SELECT receipt_id, book_name, quantity, total_price, "
          + "payment_amount, change_amount, payment_method, "
          + "cashier_name, sale_date "
          + "FROM sales "
          + "WHERE book_name LIKE ? "
          + "ORDER BY sale_date DESC";

    try (Connection con = getConnection();
         PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setString(1, "%" + search + "%");

        try (ResultSet rs = pst.executeQuery()) {

            while (rs.next()) {

                model.addRow(new Object[]{
                    rs.getInt("receipt_id"),
                    rs.getString("book_name"),
                    rs.getInt("quantity"),
                    rs.getDouble("total_price"),
                    rs.getDouble("payment_amount"),
                    rs.getDouble("change_amount"),
                    rs.getString("payment_method"),
                    rs.getString("cashier_name"),
                    rs.getTimestamp("sale_date")
                });
            }
        }

    } catch (Exception e) {

        JOptionPane.showMessageDialog(this,
                "Error searching sales: " + e.getMessage(),
                "Search Error",
                JOptionPane.ERROR_MESSAGE);
    }
}


private void setupSalesSearchAutocomplete() {
    salesSuggestionList.setSelectionMode(
            ListSelectionModel.SINGLE_SELECTION
    );

    salesSuggestionList.setBackground(new Color(255, 255, 204));
    salesSuggestionList.setSelectionBackground(
            new Color(255, 80, 80)
    );
    salesSuggestionList.setSelectionForeground(Color.WHITE);

    salesSuggestionPopup.setFocusable(false);
    salesSuggestionPopup.add(new JScrollPane(salesSuggestionList));
    salesSuggestionPopup.setPopupSize(207, 150);

    // Show suggestions whenever the user types or deletes text.
    txtSearch.getDocument().addDocumentListener(
        new DocumentListener() {
            @Override
            public void insertUpdate(DocumentEvent e) {
                showSalesSearchSuggestions();
            }

            @Override
            public void removeUpdate(DocumentEvent e) {
                showSalesSearchSuggestions();
            }

            @Override
            public void changedUpdate(DocumentEvent e) {
                showSalesSearchSuggestions();
            }
        }
    );

    // Click a suggestion to search for that book title.
    salesSuggestionList.addMouseListener(new MouseAdapter() {
        @Override
        public void mouseClicked(MouseEvent e) {
            if (e.getClickCount() == 1) {
                acceptSalesSuggestion();
            }
        }
    });

    // Press Enter to accept the selected suggestion.
    txtSearch.getInputMap().put(
            KeyStroke.getKeyStroke("ENTER"),
            "acceptSalesSuggestion"
    );

    txtSearch.getActionMap().put(
            "acceptSalesSuggestion",
            new AbstractAction() {
                @Override
                public void actionPerformed(
                        java.awt.event.ActionEvent e) {

                    if (salesSuggestionPopup.isVisible()
                            && !salesSuggestionModel.isEmpty()) {
                        acceptSalesSuggestion();
                    } else {
                        searchSales();
                    }
                }
            }
    );

    // Press Escape to close suggestions.
    txtSearch.getInputMap().put(
            KeyStroke.getKeyStroke("ESCAPE"),
            "hideSalesSuggestions"
    );

    txtSearch.getActionMap().put(
            "hideSalesSuggestions",
            new AbstractAction() {
                @Override
                public void actionPerformed(
                        java.awt.event.ActionEvent e) {
                    salesSuggestionPopup.setVisible(false);
                }
            }
    );
}

private void showSalesSearchSuggestions() {
    if (updatingSalesSearch) {
        return;
    }

    String search = txtSearch.getText().trim();

    salesSuggestionModel.clear();
    salesSuggestionPopup.setVisible(false);

    if (search.isEmpty() || !txtSearch.isShowing()) {
        return;
    }

    String sql =
            "SELECT DISTINCT book_name FROM sales "
          + "WHERE book_name LIKE ? "
          + "ORDER BY book_name LIMIT 10";

    try (Connection con = getConnection();
         PreparedStatement pst = con.prepareStatement(sql)) {

        // Suggest titles that start with the entered text.
        pst.setString(1, search + "%");

        try (ResultSet rs = pst.executeQuery()) {
            while (rs.next()) {
                salesSuggestionModel.addElement(
                        rs.getString("book_name")
                );
            }
        }

        if (!salesSuggestionModel.isEmpty()
                && txtSearch.isShowing()) {

            salesSuggestionList.setSelectedIndex(0);

            salesSuggestionPopup.show(
                    txtSearch, 0, txtSearch.getHeight()
            );
        }

    } catch (Exception e) {
        salesSuggestionPopup.setVisible(false);
        System.err.println(
                "Error loading sales suggestions: "
                + e.getMessage()
        );
    }
}

private void acceptSalesSuggestion() {
    String selected = salesSuggestionList.getSelectedValue();

    if (selected == null) {
        return;
    }

    updatingSalesSearch = true;

    try {
        txtSearch.setText(selected);
    } finally {
        updatingSalesSearch = false;
    }

    salesSuggestionPopup.setVisible(false);
    searchSales();
}


