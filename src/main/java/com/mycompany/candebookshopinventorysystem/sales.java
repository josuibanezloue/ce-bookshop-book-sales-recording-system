private int getSelectedBookId() {
    
    if (cmbBook.getSelectedItem() == null) {
        return -1;
    }

    String bookName = cmbBook.getSelectedItem().toString();

    String sql =
        "SELECT book_id FROM books "
      + "WHERE book_name = ? AND status = 'Active' "
      + "AND quantity > 0 LIMIT 1";

    try (Connection con = getConnection();
         PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setString(1, bookName);

        try (ResultSet rs = pst.executeQuery()) {
            if (rs.next()) {
                return rs.getInt("book_id");
            }
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this,
            "Error finding book: " + e.getMessage());
    }

    return -1;
}


private void calculateTotalPrice() {
    try {
        int bookId = getSelectedBookId();

        if (bookId == -1) {
            txtTotalPrice.setText("0.00");
            calculateChange();
            return;
        }

        int quantity =
            ((Number) spnQuantity.getValue()).intValue();

        String sql =
            "SELECT price FROM books "
          + "WHERE book_id = ? AND status = 'Active'";

        try (Connection con = getConnection();
             PreparedStatement pst = con.prepareStatement(sql)) {

            pst.setInt(1, bookId);

            try (ResultSet rs = pst.executeQuery()) {
                if (rs.next()) {
                    double price = rs.getDouble("price");
                    double total = price * quantity;

                    txtTotalPrice.setText(
                        String.format("%.2f", total)
                    );
                } else {
                    txtTotalPrice.setText("0.00");
                }
            }
        }

        calculateChange();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this,
            "Error calculating total: " + e.getMessage(),
            "Error",
            JOptionPane.ERROR_MESSAGE);
    }
}

private void calculateChange() {
    try {
        double total = Double.parseDouble(
            txtTotalPrice.getText().replace("₱", "").trim()
        );

        double payment =
            ((Number) spnPayment.getValue()).doubleValue();

        String method = cmbPayment.getSelectedItem() == null
                ? "Cash"
                : cmbPayment.getSelectedItem().toString();

        if (method.equals("GCash")) {
            txtChange.setText("0.00");
        } else if (payment >= total) {
            txtChange.setText(
                String.format("%.2f", payment - total)
            );
        } else {
            txtChange.setText("0.00");
        }

    } catch (NumberFormatException e) {
        txtChange.setText("0.00");
    }
}

