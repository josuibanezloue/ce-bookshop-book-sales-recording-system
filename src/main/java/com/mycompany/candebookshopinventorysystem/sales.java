    private void btnRecordSaleActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRecordSaleActionPerformed
    if (cmbBook.getSelectedItem() == null) {
        JOptionPane.showMessageDialog(this,
                "Please select a book.");
        return;
    }

    int quantity =
            ((Number) spnQuantity.getValue()).intValue();

    double payment =
            ((Number) spnPayment.getValue()).doubleValue();

    int bookId = getSelectedBookId();

    if (bookId == -1) {
        JOptionPane.showMessageDialog(this,
                "Please select a valid book.");
        return;
    }

    Connection con = null;

    try {
        con = getConnection();
        con.setAutoCommit(false);

        String bookQuery =
                "SELECT book_name, price, quantity "
              + "FROM books "
              + "WHERE book_id = ? AND status = 'Active' "
              + "FOR UPDATE";

        String bookName;
        double price;
        int availableQuantity;

        try (PreparedStatement pst =
                     con.prepareStatement(bookQuery)) {

            pst.setInt(1, bookId);

            try (ResultSet rs = pst.executeQuery()) {
                if (!rs.next()) {
                    con.rollback();
                    JOptionPane.showMessageDialog(this,
                            "Book not found or archived.");
                    return;
                }

                bookName = rs.getString("book_name");
                price = rs.getDouble("price");
                availableQuantity = rs.getInt("quantity");
            }
        }

        if (quantity > availableQuantity) {
            con.rollback();
            JOptionPane.showMessageDialog(this,
                    "Not enough stock. Available: "
                    + availableQuantity);
            return;
        }

        double totalPrice = price * quantity;
        
String paymentMethod =
        cmbPayment.getSelectedItem().toString();

if (paymentMethod.equals("GCash")
        && Math.abs(payment - totalPrice) > 0.001) {

    con.rollback();

    JOptionPane.showMessageDialog(this,
            "For GCash, payment must equal the total price.");

    return;
}

if (payment < totalPrice) {
    con.rollback();

    JOptionPane.showMessageDialog(this,
            "Insufficient payment. Total: "
            + String.format("%.2f", totalPrice));

    return;
}

double change = paymentMethod.equals("Cash")
        ? payment - totalPrice
        : 0.00;

        if (payment < totalPrice) {
            con.rollback();
            JOptionPane.showMessageDialog(this,
                    "Insufficient payment."
                    + "Total: " + String.format("%.2f", totalPrice)
                    + "\nPayment: " + String.format("%.2f", payment));
            return;
        }

        

        if (cashierName == null || cashierName.trim().isEmpty()) {
            con.rollback();
            JOptionPane.showMessageDialog(this,
                    "Unable to identify the logged-in cashier.");
            return;
        }

        String insertSQL =
                "INSERT INTO sales "
              + "(book_id, book_name, quantity, total_price, "
              + "payment_amount, change_amount, payment_method, "
              + "cashier_name, sale_date) "
              + "VALUES (?, ?, ?, ?, ?, ?, ?, ?, NOW())";

        try (PreparedStatement pst =
                     con.prepareStatement(insertSQL)) {

            pst.setInt(1, bookId);
            pst.setString(2, bookName);
            pst.setInt(3, quantity);
            pst.setDouble(4, totalPrice);
            pst.setDouble(5, payment);
            pst.setDouble(6, change);
            pst.setString(7, paymentMethod);
            pst.setString(8, cashierName);

            pst.executeUpdate();
        }

        String updateSQL =
                "UPDATE books SET quantity = quantity - ? "
              + "WHERE book_id = ? AND status = 'Active' "
              + "AND quantity >= ?";

        try (PreparedStatement pst =
                     con.prepareStatement(updateSQL)) {

            pst.setInt(1, quantity);
            pst.setInt(2, bookId);
            pst.setInt(3, quantity);

            if (pst.executeUpdate() != 1) {
                throw new SQLException(
                        "Could not update book stock.");
            }
        }

        con.commit();

        JOptionPane.showMessageDialog(this,
                "Sale recorded successfully!\n"
                + "Book: " + bookName + "\n"
                + "Quantity: " + quantity + "\n"
                + "Total: " + String.format("%.2f", totalPrice) + "\n"
                + "Payment: " + String.format("%.2f", payment) + "\n"
                + "Change: " + String.format("%.2f", change));

        loadBooks();
        loadSales();

        spnQuantity.setValue(1);
        spnPayment.setValue(0.00);
        calculateTotalPrice();

    } catch (Exception e) {
        if (con != null) {
            try {
                con.rollback();
            } catch (SQLException rollbackError) {
                e.addSuppressed(rollbackError);
            }
        }

        JOptionPane.showMessageDialog(this,
                "Error recording sale: " + e.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE);

    } finally {
        if (con != null) {
            try {
                con.close();
            } catch (SQLException e) {
                // Connection cleanup
            }
        }
    }
    
    }//GEN-LAST:event_btnRecordSaleActionPerformed

