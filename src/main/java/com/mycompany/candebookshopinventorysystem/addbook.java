    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
    String isbn = txtISBN.getText().trim();
    String bookName = txtBookName.getText().trim();
    String author = txtAuthor.getText().trim();
    String category = txtCategory.getText().trim();

    double price = ((Number) spnPrice.getValue()).doubleValue();
    int quantity = ((Number) spnQuantity.getValue()).intValue();

    // Validate text fields
    if (isbn.isEmpty() || bookName.isEmpty()
            || author.isEmpty() || category.isEmpty()) {

        JOptionPane.showMessageDialog(this,
                "Please fill in all fields.",
                "Input Error",
                JOptionPane.ERROR_MESSAGE);
        return;
    }
    
    
if (!isbn.matches("^(978|979)\\d{10}$")) {
    JOptionPane.showMessageDialog(this,
            "Invalid ISBN. Please enter a valid 13-digit ISBN starting with 978 or 979.",
            "Invalid ISBN",
            JOptionPane.WARNING_MESSAGE);
    return;
}


if (author.matches("\\d+")) {
    JOptionPane.showMessageDialog(this,
            "Author name cannot contain only numbers.",
            "Invalid Author",
            JOptionPane.WARNING_MESSAGE);
    return;
}


if (category.matches("\\d+")) {
    JOptionPane.showMessageDialog(this,
            "Category cannot contain only numbers.",
            "Invalid Category",
            JOptionPane.WARNING_MESSAGE);
    return;
}


    // Validate price and quantity
    if (price <= 0) {
        JOptionPane.showMessageDialog(this,
                "Price must be greater than zero.",
                "Invalid Price",
                JOptionPane.ERROR_MESSAGE);
        return;
    }

    if (quantity <= 0) {
        JOptionPane.showMessageDialog(this,
                "Quantity must be greater than zero.",
                "Invalid Quantity",
                JOptionPane.ERROR_MESSAGE);
        return;
    }

    String checkSql = "SELECT COUNT(*) FROM books WHERE ISBN = ?";
    String insertSql = "INSERT INTO books "
            + "(ISBN, book_name, author, category, price, quantity) "
            + "VALUES (?, ?, ?, ?, ?, ?)";

    try (Connection con = getConnection()) {

        // Check for duplicate ISBN
        try (PreparedStatement checkStmt =
                     con.prepareStatement(checkSql)) {

            checkStmt.setString(1, isbn);

            try (java.sql.ResultSet rs = checkStmt.executeQuery()) {
                if (rs.next() && rs.getInt(1) > 0) {
                    JOptionPane.showMessageDialog(this,
                            "This ISBN already exists. "
                            + "Please enter a different ISBN.",
                            "Duplicate ISBN",
                            JOptionPane.WARNING_MESSAGE);
                    return;
                }
            }
        }

        // Insert book only if ISBN does not exist
        try (PreparedStatement pst =
                     con.prepareStatement(insertSql)) {

            pst.setString(1, isbn);
            pst.setString(2, bookName);
            pst.setString(3, author);
            pst.setString(4, category);
            pst.setDouble(5, price);
            pst.setInt(6, quantity);

            pst.executeUpdate();
        }

        JOptionPane.showMessageDialog(this,
                "Book added successfully!",
                "Success",
                JOptionPane.INFORMATION_MESSAGE);

        if (booksFrame != null) {
            booksFrame.refreshBooks();
            booksFrame.setVisible(true);
        } else {
            new books().setVisible(true);
        }

        this.dispose();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this,
                "Error adding book: " + e.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE);
    }

    }//GEN-LAST:event_btnSaveActionPerformed

