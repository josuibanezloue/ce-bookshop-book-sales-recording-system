    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
  String uN, pW, query;

try{
    Class.forName("com.mysql.cj.jdbc.Driver");

    String url = "jdbc:MySQL://localhost:3306/inventory_system";
    String user= "root";
    String pass = "";

    Connection con = DriverManager.getConnection(url, user, pass);
    Statement st = con.createStatement();

    if("".equals(username.getText())){
        JOptionPane.showMessageDialog(new JFrame(), "Username is required", "Dialog", JOptionPane.ERROR_MESSAGE);
    }else if("".equals(password.getText())){
        JOptionPane.showMessageDialog(new JFrame(), "Password is required", "Dialog", JOptionPane.ERROR_MESSAGE);
    }else{
        uN = username.getText();
        pW = password.getText();
        query = "INSERT INTO tbl_users (uname, password) "
              + "VALUES ('"+uN+"','"+pW+"')";
        st.executeUpdate(query);

        con.close();
    }
}catch(Exception e){
}
    }//GEN-LAST:event_jButton1ActionPerformed

