    private void btnChangePasswordActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnChangePasswordActionPerformed
    // 1. Get input values
    String adminUsername = txtAdminUsername.getText().trim();
    String recoveryCode = txtRecoveryCode.getText().trim();

    String newPassword =
        new String(txtNewPassword.getPassword());

    String confirmPassword =
        new String(txtConfirmPassword.getPassword());

    // 2. Check empty fields
    if (adminUsername.isEmpty()
            || recoveryCode.isEmpty()
            || newPassword.isEmpty()
            || confirmPassword.isEmpty()) {

        JOptionPane.showMessageDialog(this,
                "Please fill in all fields.",
                "Missing Information",
                JOptionPane.WARNING_MESSAGE);
        return;
    }

    // 3. Check recovery code
    // Replace this with your own recovery code.
    final String ADMIN_RECOVERY_CODE = "CHANGE-THIS-CODE";

    if (!recoveryCode.equals(ADMIN_RECOVERY_CODE)) {
        JOptionPane.showMessageDialog(this,
                "Invalid recovery code.",
                "Access Denied",
                JOptionPane.ERROR_MESSAGE);
        return;
    }

    // 4. Check password length
    if (newPassword.length() < 8) {
        JOptionPane.showMessageDialog(this,
                "Password must be at least 8 characters long.",
                "Invalid Password",
                JOptionPane.WARNING_MESSAGE);
        return;
    }

    // 5. Check password confirmation
    if (!newPassword.equals(confirmPassword)) {
        JOptionPane.showMessageDialog(this,
                "Passwords do not match.",
                "Password Error",
                JOptionPane.WARNING_MESSAGE);
        return;
    }

    
    
    // 6. Check the Admin account and its current password
    String checkSQL =
        "SELECT password FROM tbl_users "
        + "WHERE username = ? AND LOWER(role) = 'admin'";

    String updateSQL =
        "UPDATE tbl_users SET password = ? "
        + "WHERE username = ? AND LOWER(role) = 'admin'";

    try (Connection con = getConnection()) {

        // Verify the Admin account
        try (PreparedStatement check =
                con.prepareStatement(checkSQL)) {

            check.setString(1, adminUsername);

            try (ResultSet rs = check.executeQuery()) {

                if (!rs.next()) {
                    JOptionPane.showMessageDialog(this,
                            "Admin account not found.",
                            "Recovery Failed",
                            JOptionPane.ERROR_MESSAGE);
                    return;
                }

                // Compare against the ORIGINAL password
                String currentPassword = rs.getString("password");

                if (newPassword.equals(currentPassword)) {
                    JOptionPane.showMessageDialog(this,
                            "Your new password cannot be the same "
                            + "as your current password.",
                            "Password Reuse",
                            JOptionPane.WARNING_MESSAGE);
                    return;
                }
            }
        }

        // Update only after all checks pass
        try (PreparedStatement update =
                con.prepareStatement(updateSQL)) {

            update.setString(1, newPassword);
            update.setString(2, adminUsername);

            int rowsUpdated = update.executeUpdate();

            if (rowsUpdated > 0) {
                JOptionPane.showMessageDialog(this,
                        "Admin password changed successfully!",
                        "Success",
                        JOptionPane.INFORMATION_MESSAGE);

                txtAdminUsername.setText("");
                txtRecoveryCode.setText("");
                txtNewPassword.setText("");
                txtConfirmPassword.setText("");

            } else {
                JOptionPane.showMessageDialog(this,
                        "Password was not changed.",
                        "Update Failed",
                        JOptionPane.ERROR_MESSAGE);
            }
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Database error: " + e.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE);
    }

    }//GEN-LAST:event_btnChangePasswordActionPerformed

