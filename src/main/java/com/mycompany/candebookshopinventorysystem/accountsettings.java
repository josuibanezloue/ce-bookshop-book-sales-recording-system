    private void btnChangePasswordActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnChangePasswordActionPerformed
    
String username = login.loggedInUsername;

if (username == null || username.trim().isEmpty()) {
    JOptionPane.showMessageDialog(this,
            "No logged-in user was found. Please log in again.",
            "Account Error",
            JOptionPane.ERROR_MESSAGE);
    return;
}

String currentPassword =
        new String(txtCurrentPassword.getPassword());
String newPassword =
        new String(txtNewPassword.getPassword());
String confirmPassword =
        new String(txtConfirmPassword.getPassword());

if (currentPassword.isEmpty()
        || newPassword.isEmpty()
        || confirmPassword.isEmpty()) {
    JOptionPane.showMessageDialog(this,
            "Please fill in all password fields.",
            "Input Error",
            JOptionPane.WARNING_MESSAGE);
    return;
}

if (newPassword.equals(currentPassword)) {
    JOptionPane.showMessageDialog(this,
            "Your new password must be different from your current password.",
            "Input Error",
            JOptionPane.WARNING_MESSAGE);
    return;
}

if (!newPassword.equals(confirmPassword)) {
    JOptionPane.showMessageDialog(this,
            "New password and confirmation do not match.",
            "Input Error",
            JOptionPane.WARNING_MESSAGE);
    return;
}

if (newPassword.length() < 8) {
    JOptionPane.showMessageDialog(this,
            "Your new password must be at least 8 characters long.",
            "Weak Password",
            JOptionPane.WARNING_MESSAGE);
    return;
}

String checkSql =
        "SELECT password FROM tbl_users WHERE username = ?";
String updateSql =
        "UPDATE tbl_users SET password = ? WHERE username = ?";

try (Connection con = getConnection()) {

    // Verify the current password
    try (PreparedStatement checkStmt =
                 con.prepareStatement(checkSql)) {

        checkStmt.setString(1, username);

        try (ResultSet rs = checkStmt.executeQuery()) {
            if (!rs.next()
                    || !rs.getString("password").equals(currentPassword)) {

                JOptionPane.showMessageDialog(this,
                        "Current password is incorrect.",
                        "Password Error",
                        JOptionPane.ERROR_MESSAGE);
                return;
            }
        }
    }

    // Update the password for this user only
    try (PreparedStatement updateStmt =
                 con.prepareStatement(updateSql)) {

        updateStmt.setString(1, newPassword);
        updateStmt.setString(2, username);

        int updated = updateStmt.executeUpdate();

        if (updated == 1) {
            JOptionPane.showMessageDialog(this,
                    "Password changed successfully!",
                    "Success",
                    JOptionPane.INFORMATION_MESSAGE);

            txtCurrentPassword.setText("");
            txtNewPassword.setText("");
            txtConfirmPassword.setText("");
        } else {
            JOptionPane.showMessageDialog(this,
                    "Password was not updated. Please try again.",
                    "Update Error",
                    JOptionPane.ERROR_MESSAGE);
        }
    }

} catch (Exception e) {
    JOptionPane.showMessageDialog(this,
            "Error changing password: " + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE);
}

    }//GEN-LAST:event_btnChangePasswordActionPerformed

    private void chkShowPasswordActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_chkShowPasswordActionPerformed
    if (chkShowPassword.isSelected()) {
        txtCurrentPassword.setEchoChar((char) 0);
        txtNewPassword.setEchoChar((char) 0);
        txtConfirmPassword.setEchoChar((char) 0);
    } else {
        txtCurrentPassword.setEchoChar('\u2022');
        txtNewPassword.setEchoChar('\u2022');
        txtConfirmPassword.setEchoChar('\u2022');
    }
    }//GEN-LAST:event_chkShowPasswordActionPerformed

