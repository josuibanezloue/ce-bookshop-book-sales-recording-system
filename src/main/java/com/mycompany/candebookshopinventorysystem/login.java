    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
    try{
    Class.forName("com.mysql.cj.jdbc.Driver");

    String url = "jdbc:mysql://localhost:3306/book_sales_recording_system";
    String user = "root";
    String pass = "";

    Connection con = DriverManager.getConnection(url, user, pass);

   if(username.getText().trim().isEmpty() && password.getText().trim().isEmpty()){
    JOptionPane.showMessageDialog(this, 
        "Username and Password are required", 
        "Login Error", 
        JOptionPane.ERROR_MESSAGE);
}else if(username.getText().trim().isEmpty()){
    JOptionPane.showMessageDialog(this, 
        "Username is required", 
        "Login Error", 
        JOptionPane.ERROR_MESSAGE);
}else if(password.getText().trim().isEmpty()){
    JOptionPane.showMessageDialog(this, 
        "Password is required", 
        "Login Error", 
        JOptionPane.ERROR_MESSAGE);
    }else{
        String uN = username.getText();
        String pW = password.getText();

        String query = "SELECT * FROM tbl_users WHERE username = ? AND password = ?";
        PreparedStatement pst = con.prepareStatement(query);
        pst.setString(1, uN);
        pst.setString(2, pW);

        ResultSet rs = pst.executeQuery();

        if(rs.next()){

    loggedInUsername = rs.getString("username");
    loggedInRole = rs.getString("role");

    JOptionPane.showMessageDialog(this, 
        "Login successful!", 
        "Success", 
        JOptionPane.INFORMATION_MESSAGE);

    new homepage().setVisible(true);
    this.dispose();
        }else{
            JOptionPane.showMessageDialog(new JFrame(), "Invalid Username or Password", "Dialog", JOptionPane.ERROR_MESSAGE);
        }

        con.close();
    }
}catch(HeadlessException | ClassNotFoundException | SQLException e){
    JOptionPane.showMessageDialog(new JFrame(), "Error: " + e.getMessage());
}   
    }//GEN-LAST:event_jButton1ActionPerformed

